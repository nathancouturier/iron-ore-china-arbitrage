"""Generate ``data/AUDIT.md``: one section per source with endpoint, terms,
row count, date range, units and a sample, then the cross-source checks.

Everything in the audit is computed from the cached raw files, so it can be
regenerated after every refresh.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from .ingest import dce, eastmoney, fred, gacc, safe, sgx, shfe, sina, worldbank
from .ingest.common import load_manifest

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "AUDIT.md"
CACHE = ROOT / "data" / "cache"


def _md_table(df: pd.DataFrame, floatfmt: str = "{:.4g}") -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, row in df.iterrows():
        cells = []
        for v in row.tolist():
            if isinstance(v, float):
                cells.append("" if np.isnan(v) else floatfmt.format(v))
            elif isinstance(v, pd.Timestamp):
                cells.append(v.date().isoformat())
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _retrieved(prefix: str) -> str:
    m = load_manifest()
    stamps = sorted(v["retrieved_at"] for k, v in m.items() if k.startswith(prefix))
    if not stamps:
        return "not retrieved"
    return stamps[0] if stamps[0] == stamps[-1] else f"{stamps[0]} to {stamps[-1]}"


def section(
    title: str, endpoint: str, terms: str, units: str, df: pd.DataFrame, date_col: str, prefix: str, notes: str = ""
) -> str:
    d = pd.to_datetime(df[date_col])
    sample = pd.concat([df.head(2), df.tail(2)])
    out = [
        f"### {title}",
        "",
        f"- Endpoint: {endpoint}",
        f"- Retrieved (UTC): {_retrieved(prefix)}",
        f"- Terms: {terms}",
        f"- Units: {units}",
        f"- Rows: {len(df):,}; range {d.min().date()} to {d.max().date()}",
    ]
    if notes:
        out.append(f"- Notes: {notes}")
    out += ["", _md_table(sample), ""]
    return "\n".join(out)


def build() -> str:
    parts = [
        "# Data audit",
        "",
        "Generated by `pipeline/audit.py` from the cached raw files. Raw files and their",
        "SHA-256 hashes are listed in `data/raw/manifest.json`. Files from exchanges and",
        "other third parties are re-fetched by the pipeline and not committed.",
        "",
        "## Sources",
        "",
    ]
    for sid, note in fred.SERIES.items():
        df = fred.read(sid).dropna()
        parts.append(
            section(
                f"FRED {sid}",
                f"{fred.URL}?id={sid}",
                "FRED, public; original publisher credited (IMF, Federal Reserve, EIA, New York Fed)",
                note,
                df,
                "date",
                f"fred/{sid}",
            )
        )
    wb = worldbank.read()
    parts.append(
        section(
            "World Bank Pink Sheet, iron ore",
            worldbank.PAGE + " (monthly workbook, sheet Monthly Prices)",
            "CC BY 4.0",
            "USD per dry metric tonne, monthly average, 62% Fe fines CFR China",
            wb.dropna(),
            "date",
            "worldbank/",
        )
    )
    panel = dce.read_panel(("I", "J", "JM"))
    parts.append(
        section(
            "DCE annual history files (I, J, JM)",
            dce.PAGE + " (one file per variety and year, downloaded by scripts/dce_history.mjs)",
            "Exchange data, not redistributed; re-fetched by the pipeline",
            "Prices RMB per tonne; volume and open interest in lots, double-sided as published",
            panel[["product", "contract", "date", "settle", "close", "volume", "oi"]],
            "date",
            "dce/",
            "Contracts per product: "
            + ", ".join(f"{k} {v}" for k, v in panel.groupby("product")["contract"].nunique().items()),
        )
    )
    sn = sina.read_all()
    parts.append(
        section(
            "Sina per-contract daily history (I, J, JM, RB, HC)",
            sina.URL + "?symbol=I2601",
            "Third-party data, not redistributed; re-fetched by the pipeline",
            "Prices RMB per tonne; volume and open interest in lots as published (double-sided before 2020, single-sided after)",
            sn.sort_values(["date", "contract"]),
            "date",
            "sina/",
            f"{sn['contract'].nunique()} contracts; settlement stored as 0 when missing (treated as missing)",
        )
    )
    sh = shfe.read_panel()
    if not sh.empty:
        parts.append(
            section(
                "SHFE official daily files (RB, HC)",
                shfe.URL.format(d="YYYYMMDD"),
                "Exchange data, not redistributed; re-fetched by the pipeline",
                "Prices RMB per tonne; volume and open interest in lots",
                sh.sort_values(["date", "contract"]),
                "date",
                "shfe/",
                f"{sh['date'].nunique()} trading days cached",
            )
        )
    for name, label in [("bci", "Baltic Capesize Index"), ("bdi", "Baltic Dry Index")]:
        df = eastmoney.read(name)
        parts.append(
            section(
                f"{label} ({name.upper()})",
                eastmoney.URL + f" (RPT_INDUSTRY_INDEX, {eastmoney.INDICATORS[name]})",
                "Baltic Exchange index values republished by East Money; not redistributed",
                "Index points",
                df,
                "date",
                f"eastmoney/{name}",
            )
        )
    cp = safe.read()
    parts.append(
        section(
            "PBoC USD/CNY central parity",
            safe.URL + " (POST startDate, endDate)",
            "Official publication (SAFE); raw pages not committed, derived series committed",
            "CNY per USD (published per 100 USD)",
            cp,
            "date",
            "safe/",
        )
    )
    imp = gacc.read()
    parts.append(
        section(
            "China Customs (GACC) monthly iron ore imports",
            gacc.BASE + "/statics/report/monthly{year}.html, table (14); preliminary{year}.html, table (6)",
            "Official statistics; raw pages not committed, derived series committed",
            "Iron ores and concentrates, 10,000 tonnes as published (million tonnes in the derived series)",
            imp,
            "start",
            "gacc/",
            "January and February 2020 published together; September and October 2024 and the latest month "
            "from the preliminary release",
        )
    )
    fef = sgx.read_fef()
    parts.append(
        section(
            "SGX iron ore futures (FEF) daily settlement",
            sgx.URL.format(id="{file_id}"),
            "Exchange data, not redistributed; re-fetched by the pipeline",
            "USD per dry metric tonne (62% Fe fines CFR China index futures); pre-2018 files carry two implied decimals",
            fef,
            "date",
            "sgx/",
            f"{fef['date'].nunique()} trading days",
        )
    )
    checks_path = ROOT / "data" / "derived" / "cross_checks.json"
    if checks_path.exists():
        checks = json.loads(checks_path.read_text())
        parts += ["## Cross-source checks", ""]
        for c in checks:
            parts += [f"### {c['title']}", "", c["text"], ""]
            if c.get("table"):
                fmt = "{:.6g}" if c["title"].startswith("China Customs") else "{:.4g}"
                parts += [_md_table(pd.DataFrame(c["table"]), fmt), ""]
    return "\n".join(parts) + "\n"


def run() -> dict[str, str]:
    """The audit describes the raw files, so it is regenerated only when they are
    all cached (a full rebuild); otherwise the committed audit is kept."""
    try:
        text = build()
    except (FileNotFoundError, ValueError, KeyError) as exc:
        return {"audit": f"kept from last full rebuild ({type(exc).__name__})"}
    OUT.write_text(text, encoding="utf-8")
    return {"audit": f"written {OUT.relative_to(ROOT)}"}
